"""Alembic's entry point.

Two jobs beyond the generated template:

1. **Take the database URL from the application's own settings**, so there is
   exactly one place the backend's database is configured. `alembic.ini` leaves
   `sqlalchemy.url` empty on purpose.

2. **Import the models**, so `Base.metadata` is populated before autogenerate
   inspects it. Forgetting this is the classic Alembic failure: autogenerate
   compares the live database against an *empty* metadata, concludes nothing
   has changed, and writes a migration with two `pass` statements. It looks
   like success.

Because this imports `app.*`, Alembic must be run from `backend/`:

    .venv\\Scripts\\python -m alembic revision --autogenerate -m "..."
    .venv\\Scripts\\python -m alembic upgrade head
    .venv\\Scripts\\python -m alembic downgrade -1
"""

import asyncio
from logging.config import fileConfig

from alembic import context
from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import async_engine_from_config

from app.core.config import get_settings
from app.db.base import Base

# Importing for the side effect of registering the tables on Base.metadata.
# Without this line every autogenerated migration is empty. Lint rules that
# remove "unused" imports will break migrations silently, hence the noqa.
import app.db.models  # noqa: F401

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

# One source of truth for the DSN — but only as a *fallback*.
#
# A caller may have set the URL already: the test suite points Alembic at
# `myrag_test` before invoking it, and `alembic -x` or a programmatic `Config`
# can do the same. Overwriting that unconditionally is a genuinely nasty bug —
# the migration silently runs against the development database instead, the
# intended one stays empty, and the failure surfaces later as "relation does
# not exist" somewhere unrelated.
#
# The settings object also normalises a bare `postgresql://` to the asyncpg
# driver, so a URL pasted from a managed provider works here too.
if not config.get_main_option("sqlalchemy.url", None):
    config.set_main_option("sqlalchemy.url", get_settings().database_url)

target_metadata = Base.metadata


def _configure(connection: Connection | None = None, **kwargs: object) -> None:
    """Shared comparison settings for both online and offline runs.

    `compare_type` and `compare_server_default` are **off by default**, and
    without them autogenerate silently misses a column whose type or default
    changed — producing an empty migration that looks correct.

    What autogenerate still cannot see, and what therefore has to be written by
    hand:

      - renames. A column rename is detected as a drop plus an add, which
        compiles, runs, and destroys the data in that column.
      - the contents of a CHECK constraint, including the list of allowed
        status values. Adding `queued` at stage 1.3 is a hand-written
        migration.

    Which is the real rule here: read every generated migration before running
    it. Autogenerate is a first draft.
    """
    context.configure(
        connection=connection,
        url=config.get_main_option("sqlalchemy.url"),
        target_metadata=target_metadata,
        compare_type=True,
        compare_server_default=True,
        **kwargs,
    )


def run_migrations_offline() -> None:
    """Emit SQL to stdout instead of executing it.

    `alembic upgrade head --sql` produces a script for a DBA to review and run
    — which is how schema changes reach a database you are not allowed to
    connect to directly. Not used yet; it is the generated default and costs
    nothing to keep correct.
    """
    _configure(literal_binds=True, dialect_opts={"paramstyle": "named"})

    with context.begin_transaction():
        context.run_migrations()


def do_run_migrations(connection: Connection) -> None:
    _configure(connection=connection)

    # Postgres has transactional DDL, so a failed migration leaves the schema
    # untouched rather than half-applied. Most other databases do not, which is
    # why migrations elsewhere need to be written to be re-runnable.
    with context.begin_transaction():
        context.run_migrations()


async def run_async_migrations() -> None:
    """Run migrations through the async driver.

    Alembic itself is synchronous and our driver is not, so the connection is
    opened asynchronously and the migration body is handed to `run_sync`, which
    executes it on the greenlet that the async engine provides.

    The alternative is installing psycopg2 purely for migrations, which means
    two drivers, two DSN formats, and two chances for them to disagree about
    which database they are pointing at.

    `NullPool`: a migration run is one connection, used once, by a process that
    exits. Pooling it would only delay shutdown.
    """
    connectable = async_engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )

    async with connectable.connect() as connection:
        await connection.run_sync(do_run_migrations)

    await connectable.dispose()


def run_migrations_online() -> None:
    asyncio.run(run_async_migrations())


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
